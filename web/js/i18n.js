  var AVAILABLE = ['zh', 'en'];
  var locale = 'zh';

  /**
   * 翻译。变量用 {name} 占位。
   * 找不到 key 时返回 key 本身，并在控制台告警 —— 便于开发期发现漏翻。
   */
  function t(key, vars) {
    var table = STR[locale] || STR.zh;
    var s = table[key];
    if (s === undefined) {
      if (STR.zh[key] === undefined) {
        console.warn('[i18n] 缺少文案 key:', key);
        return key;
      }
      s = STR.zh[key];
    }
    if (vars) {
      s = s.replace(/\{(\w+)\}/g, function (m, name) {
        return Object.prototype.hasOwnProperty.call(vars, name) ? String(vars[name]) : m;
      });
    }
    return s;
  }

  function setLocale(next) {
    if (AVAILABLE.indexOf(next) === -1) next = 'zh';
    locale = next;
    document.documentElement.setAttribute('lang', next === 'zh' ? 'zh-CN' : 'en');
    apply();
  }

  /**
   * 把 [data-i18n] 元素的文本、[data-i18n-title] 的 title、
   * [data-i18n-placeholder] 的 placeholder 全部按当前语言刷新。
   */
  function apply(root) {
    var scope = root || document;

    scope.querySelectorAll('[data-i18n]').forEach(function (el) {
      el.textContent = t(el.getAttribute('data-i18n'));
    });

    scope.querySelectorAll('[data-i18n-title]').forEach(function (el) {
      el.setAttribute('title', t(el.getAttribute('data-i18n-title')));
    });

    scope.querySelectorAll('[data-i18n-aria]').forEach(function (el) {
      el.setAttribute('aria-label', t(el.getAttribute('data-i18n-aria')));
    });

    scope.querySelectorAll('[data-i18n-placeholder]').forEach(function (el) {
      el.setAttribute('placeholder', t(el.getAttribute('data-i18n-placeholder')));
    });
  }

  /** 让外部（如设置页）能拿到所有可用语言 */
  function getLocale() {
    return locale;
  }

  /** 按浏览器语言猜一个默认值 */
  function detect() {
    var nav = (navigator.language || 'zh').toLowerCase();
    return nav.indexOf('zh') === 0 ? 'zh' : 'en';
  }

  MM.i18n = {
    t: t,
    setLocale: setLocale,
    getLocale: getLocale,
    apply: apply,
    detect: detect,
    AVAILABLE: AVAILABLE,
    STR: STR
  };
